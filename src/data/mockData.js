export function buildWhatsAppLink(phone, message) {
  const digits = phone.replace(/[^\d]/g, "");
  return `https://wa.me/${digits}?text=${encodeURIComponent(message)}`;
}

// Same in/low/critical thresholds the seed inventoryItems above were authored against
// (ratio of stock on hand to the reorder level), reused when new items are added.
export function deriveStockStatus(stockQty, reorderLevel) {
  if (reorderLevel <= 0) return "in-stock";
  const ratio = stockQty / reorderLevel;
  if (ratio <= 0.3) return "critical";
  if (ratio < 1) return "low";
  return "in-stock";
}
